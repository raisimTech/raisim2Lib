/// The library grade with exactly these properties, or nullptr.
inline const MaterialGrade* findMaterialGrade(double youngsModulus,
                                              double poissonRatio,
                                              double density, double strength) {
  for (const auto& category : materialLibrary())
    for (const auto& grade : category.grades)
      if (grade.youngsModulus == youngsModulus &&
          grade.poissonRatio == poissonRatio && grade.density == density &&
          grade.strength == strength)
        return &grade;
  return nullptr;
}
