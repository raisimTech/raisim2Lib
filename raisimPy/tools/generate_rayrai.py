def quote(s):return json.dumps(s,ensure_ascii=True)
def short(q):return q.split('::')[-1]
def py_path(q):return q.removeprefix('raisin::').split('::')
def scope(q):
 p=py_path(q)[:-1];return 'm'+''.join('.attr('+quote(n)+')' for n in p)
def binding_type(q):
 return 'RenderOverridesValue' if q=='raisin::RayraiWindow::RenderOverrides' else (f'Handle<{q}>' if q in GPU else q)
def bound(q):
 t=binding_type(q)
 return f'bound_class<{t}>({scope(q)}, {quote(short(q))})'

def bare(t):return re.sub(r'^(const )|[ &]+$','',t).strip()
def ctype(info):
 t=info['canonical']
 original=info['type']
 # Preserve platform-sized aliases: libclang's Linux canonical unsigned long
 # is not size_t/uint64_t on Windows. Qualify nested record names canonically.
 for alias in ('size_t','uint64_t','uintmax_t'):
  if re.search(r'\b'+alias+r'\b',original):
   t=re.sub(r'\bunsigned long\b','std::'+alias,t)
 if 'std::chrono::' in original:
  return original
 return t

def default_expr(a,q):
 d=a['source'].split('=',1)[1].strip()
 if d=='nullptr':return 'py::none()'
 t=bare(ctype(a))
 if d.startswith('{'):d=f'{binding_type(t) if t in index else t}{d}'
 for name in ['PrimitiveTopology','RenderMode','SensorStorageMode','ThreadingMode','VisibilityRangeFadeMode']:
  if d.startswith(name+'::'):d=q+'::'+d
 return d

def arg_annotation(a,q):
 n=a['name'] or 'value'
 suffix='.none()' if a['canonical'].endswith(' *') and a['canonical']!='const char *' else ''
 if '=' not in a['source']:return f'py::arg({quote(n)})'+suffix
 d=default_expr(a,q)
 return f'py::arg({quote(n)})'+suffix+f' = {d}'

