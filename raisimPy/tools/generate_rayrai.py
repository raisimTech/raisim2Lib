# Keep translation units small enough for ordinary workstation builds.
def write_group(prefix,lines,chunk):
 names=[]
 for i,start in enumerate(range(0,len(lines),chunk)):
  fn=f'{prefix}_{i:03d}';names.append(fn)
  save(OUT/(fn+'.cpp'),'// Generated by tools/generate_rayrai.py; do not edit.\n#include "conversion.hpp"\nnamespace rayrai_py {\nvoid '+fn+'(py::module_& m) {\n'+ '\n'.join(lines[start:start+chunk])+'\n}\n}\n')
 return names
