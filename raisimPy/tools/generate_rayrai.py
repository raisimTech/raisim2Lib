def public(r):
 q=r['name']
 if not r.get('public',True) or q in INTERNAL or q.startswith(('rayrai_detail::','raisin::rayrai_internal::','raisim::')):return False
 for p in index:
  if q.startswith(p+'::') and (not index[p].get('public',True) or p in INTERNAL):return False
