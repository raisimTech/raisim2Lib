  if k=='FieldDecl':
   if q=='raisin::RayraiWindow::ImportVisualSceneOptions' and n=='report':
    log(q,m,'excluded','Passed as an explicit report argument to importVisualScene');continue
   if q not in GPU and q!='raisin::RayraiWindow::RenderOverrides' and any(re.search(r'(?<![\w:])'+re.escape(g)+r'(?![\w:])',t) for g in GPU):
    raise SystemExit('Unmanaged GPU data member requires an adapter: '+q+'::'+n)
   if n in opaque_fields or q=='raisin::assimp::AsyncModelLoadResult' and n=='geometry' or q.startswith('raisin::Physics') and n in ('world','object') or 'void>' in t or 'rayrai_internal::' in t:
    log(q,m,'excluded','Opaque implementation ownership token');continue
   if q in GPU and ('std::' in t and any(g in t for g in GPU)):
    pass
   definitions.append(f'{{auto c={bound(q)}; field(c,{quote(n+"_" if keyword.iskeyword(n) else n)}, &{q}::{n});}}');log(q,m,'generated')
  elif k=='VarDecl' and 'constexpr' in m['source']:
   definitions.append(f'{scope(q)}.attr({quote(short(q))}).attr({quote(n)})=py::cast({q}::{n});');log(q,m,'generated')
  elif k=='TypeAliasDecl' and t in index and public(index[t]):
   pp=py_path(t);expr='m'+''.join('.attr('+quote(p)+')'for p in pp)
   aliases.append(f'{scope(q)}.attr({quote(short(q))}).attr({quote(n)})={expr};');log(q,m,'generated')
  elif k=='CXXMethod':emit_method(q,m)
  elif k=='CXXConstructor':
   if q=='raisin::RayraiWindow':log(q,m,'manual');continue
   if m.get('deleted') or any(bare(a['canonical'])==q for a in m['args']):log(q,m,'excluded','Deleted/copy/move constructor');continue
   sig=tuple(a['canonical'] for a in m['args'])
   if sig in seen_ctor:continue
   seen_ctor.add(sig)
   params=[];ann=[];call=[];ctor_setup=[]
   for i,a in enumerate(m['args']):
    params.append(f'Arg<{ctype(a)}> a{i}');ann.append(arg_annotation({**a,'name':a['name']or('value'+str(i))},q));ctor_setup.append(f'decltype(auto) n{i}=unwrap<{ctype(a)}>(a{i},state);');call.append(f'std::move(n{i})' if ctype(a).endswith(' &&') else f'n{i}')
   if q in GPU:
    params=['Handle<'+q+'>* self','const Viewer& viewer']+params;ann=['py::arg("viewer")']+ann
    body=f'auto state=viewer.state; Guard guard(state); '+ ' '.join(ctor_setup)+ f' auto value=std::shared_ptr<{q}>(new {q}('+', '.join(call)+')); new(self) Handle<'+q+'>(own(state,std::move(value)));'
   else:
    params=[q+'* self']+params;body='auto state=current_state(); Guard guard(state,false); '+ ' '.join(ctor_setup)+' new(self) '+q+'('+', '.join(call)+');'
   definitions.append(f'{bound(q)}.def("__init__", []({", ".join(params)}){{ {body} }}'+(', '+', '.join(ann)if ann else'')+');');log(q,m,'generated')

